#!/usr/bin/env bash
set -euo pipefail

container="${RESOLVE_CONTAINER:-davincibox-docker}"
container_user="${RESOLVE_USER:-$(id -un)}"
resolve_dir="${RESOLVE_DIR:-/opt/resolve}"
uid="$(id -u)"
display="${DISPLAY:-:0}"
xauthority="${XAUTHORITY:-$HOME/.Xauthority}"
resolve_home="${RESOLVE_HOME:-${HOME}/.local/share/davinci-resolve-21-box-home}"
resolve_xdg_config_home="${RESOLVE_XDG_CONFIG_HOME:-${resolve_home}/.config}"
resolve_xdg_data_home="${RESOLVE_XDG_DATA_HOME:-${resolve_home}/.local/share}"
resolve_xdg_cache_home="${RESOLVE_XDG_CACHE_HOME:-${resolve_home}/.cache}"
resolve_lock_dir="${RESOLVE_LOCK_DIR:-${resolve_home}/.davinci-resolve-docker.lock}"
xdg_runtime="/run/user/${uid}"
pulse_server="${PULSE_SERVER:-unix:${xdg_runtime}/pulse/native}"
dbus_session="${DBUS_SESSION_BUS_ADDRESS:-unix:path=${xdg_runtime}/bus}"
audio_mode="${RESOLVE_AUDIO_MODE:-system}"
alsa_config_path=""
lock_acquired=0

die() {
  echo "davinci-resolve-docker: $*" >&2
  exit 1
}

need_absolute_path() {
  case "$2" in
    /*) ;;
    *) die "$1 must be an absolute path: $2" ;;
  esac
}

case "${1:-}" in
  --audio=*)
    audio_mode="${1#--audio=}"
    shift
    ;;
  --audio-system)
    audio_mode="system"
    shift
    ;;
  --audio-auto)
    audio_mode="auto"
    shift
    ;;
  --audio-null)
    audio_mode="null"
    shift
    ;;
esac

cleanup_lock() {
  if [ "${lock_acquired}" = "1" ] && [ -d "${resolve_lock_dir}" ]; then
    local owner_pid
    owner_pid="$(cat "${resolve_lock_dir}/pid" 2>/dev/null || true)"
    if [ "${owner_pid}" = "$$" ]; then
      rm -rf -- "${resolve_lock_dir}"
    fi
  fi
}

cleanup_audio() {
  if [ -n "${alsa_config_path}" ]; then
    rm -f -- "${alsa_config_path}"
  fi
}

cleanup_all() {
  cleanup_audio
  cleanup_lock
}

handle_signal() {
  local status="$1"
  cleanup_all
  exit "${status}"
}

acquire_lock() {
  while ! mkdir "${resolve_lock_dir}" 2>/dev/null; do
    local owner_pid
    owner_pid="$(cat "${resolve_lock_dir}/pid" 2>/dev/null || true)"

    if [[ "${owner_pid}" =~ ^[0-9]+$ ]] && kill -0 "${owner_pid}" 2>/dev/null; then
      die "Resolve is already running for RESOLVE_HOME=${resolve_home} (launcher pid ${owner_pid})."
    fi

    echo "davinci-resolve-docker: removing stale Resolve lock at ${resolve_lock_dir}" >&2
    rm -rf -- "${resolve_lock_dir}"
  done

  lock_acquired=1
  printf '%s\n' "$$" > "${resolve_lock_dir}/pid"
  printf '%s\n' "${container}" > "${resolve_lock_dir}/container"
  printf '%s\n' "${resolve_home}" > "${resolve_lock_dir}/resolve_home"
  date -Is > "${resolve_lock_dir}/created_at" 2>/dev/null || date > "${resolve_lock_dir}/created_at"

  trap cleanup_all EXIT
  trap 'handle_signal 129' HUP
  trap 'handle_signal 130' INT
  trap 'handle_signal 143' TERM
}

audio_socket_path() {
  case "${pulse_server}" in
    unix:/*) printf '%s\n' "${pulse_server#unix:}" ;;
    unix:path=*) printf '%s\n' "${pulse_server#unix:path=}" ;;
    *) return 1 ;;
  esac
}

remove_generated_file() {
  local path="$1"
  if [ -f "${path}" ] && head -n 1 "${path}" | grep -qx '# Generated by davinci-resolve-docker.*'; then
    rm -f -- "${path}"
  fi
}

remove_generated_audio_config() {
  remove_generated_file "${resolve_home}/.asoundrc"
  remove_generated_file "${resolve_xdg_config_home}/pulse/client.conf"
  remove_generated_file "${resolve_home}/.davinci-resolve-docker-audio-mode"
}

configure_audio() {
  local socket_path selected_mode

  case "${audio_mode}" in
    auto|system|pulse|null) ;;
    *) die "invalid audio mode '${audio_mode}'. Use system, auto, pulse, or null." ;;
  esac

  selected_mode="${audio_mode}"
  if [ "${selected_mode}" = "auto" ]; then
    if socket_path="$(audio_socket_path)" && [ -S "${socket_path}" ]; then
      selected_mode="system"
    else
      selected_mode="null"
    fi
  fi

  remove_generated_audio_config

  case "${selected_mode}" in
    system|pulse)
      if socket_path="$(audio_socket_path)" && [ ! -S "${socket_path}" ]; then
        echo "davinci-resolve-docker: warning: Pulse socket is unavailable: ${socket_path}" >&2
      fi
      ;;
    null)
      alsa_config_path="$(mktemp "${TMPDIR:-/tmp}/davinci-resolve-alsa-null.XXXXXX")"
      cat > "${alsa_config_path}" <<'EOF'
pcm.!default {
    type null
}

ctl.!default {
    type hw
    card 0
}
EOF
      ;;
  esac

  printf '%s\n' "${selected_mode}" > "${resolve_home}/.davinci-resolve-docker-audio-mode"
}

resolve_amd_opencl_lib() {
  if [ -n "${ROCM_OPENCL_LIB:-}" ]; then
    [ -e "${ROCM_OPENCL_LIB}" ] || die "ROCM_OPENCL_LIB does not exist: ${ROCM_OPENCL_LIB}"
    printf '%s\n' "${ROCM_OPENCL_LIB}"
    return 0
  fi

  local icd line path
  for icd in /etc/OpenCL/vendors/*.icd; do
    [ -e "${icd}" ] || continue
    while IFS= read -r line || [ -n "${line}" ]; do
      line="${line%%#*}"
      line="${line#"${line%%[![:space:]]*}"}"
      line="${line%"${line##*[![:space:]]}"}"
      [ -n "${line}" ] || continue
      [[ "${line}" == *amd* || "${line}" == *amdocl* ]] || continue

      if [[ "${line}" = /* && -e "${line}" ]]; then
        printf '%s\n' "${line}"
        return 0
      fi

      path="$(ldconfig -p 2>/dev/null | awk -v lib="${line}" '$1 == lib { print $NF; exit }')"
      if [ -n "${path}" ] && [ -e "${path}" ]; then
        printf '%s\n' "${path}"
        return 0
      fi
    done < "${icd}"
  done

  for path in /opt/rocm*/lib/libamdocl64.so /opt/rocm*/core-*/lib/opencl/libamdocl64.so /opt/amdgpu*/lib*/libamdocl64.so; do
    [ -e "${path}" ] || continue
    printf '%s\n' "${path}"
    return 0
  done

  path="$(find -L /opt/rocm* /opt/amdgpu /usr/lib /usr/lib64 /usr/lib/x86_64-linux-gnu \
    -type f -name 'libamdocl64.so*' -print -quit 2>/dev/null || true)"
  [ -n "${path}" ] && [ -e "${path}" ] || die "could not find AMD ROCm OpenCL library. Verify host clinfo shows an AMD GPU."
  printf '%s\n' "${path}"
}

host_opencl="$(resolve_amd_opencl_lib)"
container_opencl="/run/host${host_opencl}"

need_absolute_path "RESOLVE_HOME" "${resolve_home}"
need_absolute_path "RESOLVE_XDG_CONFIG_HOME" "${resolve_xdg_config_home}"
need_absolute_path "RESOLVE_XDG_DATA_HOME" "${resolve_xdg_data_home}"
need_absolute_path "RESOLVE_XDG_CACHE_HOME" "${resolve_xdg_cache_home}"
need_absolute_path "RESOLVE_LOCK_DIR" "${resolve_lock_dir}"
mkdir -p \
  "${resolve_home}" \
  "${resolve_xdg_config_home}" \
  "${resolve_xdg_data_home}" \
  "${resolve_xdg_cache_home}"

configure_audio
acquire_lock

if ! docker container inspect "${container}" >/dev/null 2>&1; then
  die "container '${container}' does not exist. Run scripts/setup-davinci-resolve-docker.sh from the repo first."
fi

if [ "$(docker inspect -f '{{.State.Running}}' "${container}")" != "true" ]; then
  docker start "${container}" >/dev/null
fi

docker exec -u root \
  -e RESOLVE_DIR_IN_CONTAINER="/run/host${resolve_dir}" \
  -e CONTAINER_OPENCL="${container_opencl}" \
  "${container}" bash -lc '
  set -e
  if [ -e /opt/resolve ] && [ ! -L /opt/resolve ]; then
    echo "/opt/resolve exists in the container and is not a symlink" >&2
    exit 1
  fi
  ln -sfn "${RESOLVE_DIR_IN_CONTAINER}" /opt/resolve
  mkdir -p /etc/OpenCL/vendors
  printf "%s\n" "${CONTAINER_OPENCL}" > /etc/OpenCL/vendors/amdocl64-host.icd
'

set +e
docker_env_args=()
if [ -n "${alsa_config_path}" ]; then
  docker_env_args=(-e "ALSA_CONFIG_PATH=${alsa_config_path}")
fi

docker exec -u "${container_user}" \
  -e DISPLAY="${display}" \
  -e XAUTHORITY="${xauthority}" \
  -e HOME="${resolve_home}" \
  -e XDG_CONFIG_HOME="${resolve_xdg_config_home}" \
  -e XDG_DATA_HOME="${resolve_xdg_data_home}" \
  -e XDG_CACHE_HOME="${resolve_xdg_cache_home}" \
  -e XDG_RUNTIME_DIR="${xdg_runtime}" \
  -e PULSE_SERVER="${pulse_server}" \
  "${docker_env_args[@]}" \
  -e DBUS_SESSION_BUS_ADDRESS="${dbus_session}" \
  -e QT_X11_NO_MITSHM="${QT_X11_NO_MITSHM:-1}" \
  -w /opt/resolve \
  "${container}" \
  /opt/resolve/bin/resolve "$@"
status="$?"
set -e
exit "${status}"
